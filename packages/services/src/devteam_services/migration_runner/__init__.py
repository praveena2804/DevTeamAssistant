"""Migration Runner (deterministic service; Part E plan §1 E.3; D-16).

Checks a generated application's Alembic migrations inside the sandbox against a **disposable SQLite**
database: upgrade → downgrade → upgrade (``alembic_upgrade``), or proposes an autogenerated revision
(``alembic_autogenerate``) without applying it. PostgreSQL validation is refused until Part K (D-16).
The Database Developer never applies migrations; this service does, in a throw-away container.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from dataclasses import dataclass
from typing import Any

from devteam_core.contracts.sandbox import MigrationCheckRequest, SandboxExecutionStatus
from devteam_harness.errors import PolicyDeniedError
from devteam_harness.iam.principals import ServiceName, ServicePrincipal
from devteam_harness.sandbox.service import Evidence, ExecutionOutcome, ExecutionOwner, SandboxService

PRINCIPAL = ServicePrincipal(ServiceName.MIGRATION_RUNNER).id


@dataclass(frozen=True, slots=True)
class MigrationCheck:
    outcome: ExecutionOutcome
    report: dict[str, Any]  # migration.json written by the in-image checker (untrusted, informational)

    @property
    def passed(self) -> bool:
        execution = self.outcome.execution
        return (
            execution.status is SandboxExecutionStatus.COMPLETED
            and execution.exit_code == 0
            and self.report.get("status") == "passed"
        )


class MigrationRunner:
    def __init__(self, sandbox: SandboxService) -> None:
        self._sandbox = sandbox

    def check(
        self,
        request: MigrationCheckRequest | Mapping[str, Any],
        *,
        files: Mapping[str, bytes],
        owner: ExecutionOwner,
        evidence: Evidence,
    ) -> MigrationCheck:
        raw = (
            dict(request) if isinstance(request, Mapping) else request.model_dump(exclude={"schema_version"})
        )
        if raw.get("engine", "sqlite") != "sqlite":
            raise PolicyDeniedError(
                "sandbox.postgresql_not_available",
                "PostgreSQL validation arrives in Part K (D-16); only a disposable SQLite database is used",
                "deny.d16",
            )
        parsed = MigrationCheckRequest.model_validate(raw)
        args = (
            {"message": parsed.message or "generated_change"}
            if parsed.recipe == "alembic_autogenerate"
            else {}
        )
        outcome = self._sandbox.execute(
            recipe=parsed.recipe,
            args=args,
            files=files,
            owner=owner,
            principal_id=PRINCIPAL,
            evidence=evidence,
        )
        try:
            report = json.loads(outcome.outputs.get("migration.json", b"{}"))
        except ValueError:
            report = {}
        return MigrationCheck(outcome=outcome, report=report if isinstance(report, dict) else {})


__all__ = ["PRINCIPAL", "MigrationCheck", "MigrationRunner"]
