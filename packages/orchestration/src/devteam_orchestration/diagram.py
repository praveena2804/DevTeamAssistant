"""Generate ``docs/architecture/orchestration.md`` from the compiled graph (D.3; plan §5).

Uses LangGraph's offline ``draw_mermaid()`` text output only; never ``draw_mermaid_png`` (that calls a web
service). ``python -m devteam_orchestration.diagram`` rewrites the file; the test suite checks that the
committed file matches the compiled graph.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any, cast

from devteam_core.contracts.orchestration import NODE_KIND, NODE_SUBGRAPH, NodeName
from devteam_core.paths import find_repo_root
from devteam_orchestration.graph import build_graph

DOC = Path("docs") / "architecture" / "orchestration.md"

HEADER = """# Orchestration (Part D)

This file is generated by `uv run python -m devteam_orchestration.diagram` from the compiled LangGraph
graph. Do not edit it by hand; `packages/orchestration/tests/test_graph.py` fails when it is out of date.

**How to read it.** One graph, `project_run`. Its edges are exactly the static allowed-transition table
(`devteam_core.contracts.orchestration.ALLOWED_TRANSITIONS`). Dotted edges are choices a node makes; every
choice is checked against the table. Gate nodes stop the run and wait for a human decision. Every path
into Build passes `freeze_spec` (or `freeze_change_spec`) and `build_entry_guard`; every Build and
Delivery node re-checks the frozen, approved specification when it starts.

**Agents.** Exactly ten agent nodes, one per agent (ten-agent layer L4). They run only through the Agent
Executor and the real local Ollama provider (D-44); nothing is simulated. Service steps marked "stand-in"
report only that they did not run, and name the part that delivers them.

"""


def mermaid() -> str:
    graph = build_graph(cast(Any, None), None)  # nodes are not executed; no runtime is needed
    return str(graph.get_graph().draw_mermaid())


def node_table() -> str:
    rows = ["| Node | Kind | Subgraph |", "|---|---|---|"]
    rows += [f"| `{n.value}` | {NODE_KIND[n].value} | {NODE_SUBGRAPH[n].value} |" for n in NodeName]
    return "\n".join(rows)


def render() -> str:
    return (
        HEADER
        + "## Diagram\n\n```mermaid\n"
        + mermaid().strip()
        + "\n```\n\n## Nodes\n\n"
        + node_table()
        + "\n"
    )


def main() -> int:
    path = find_repo_root() / DOC
    path.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
